def num(x):
    """float or None (JSON-safe)."""
    if x is None:
        return None
    try:
        x = float(x)
    except (TypeError, ValueError):
        return None
    return None if (math.isnan(x) or math.isinf(x)) else round(x, 4)


def to_num(series):
    return pd.to_numeric(series.str.replace("%", "", regex=False).str.strip(), errors="coerce")


def region_sort_key(r):
    return (REGION_ORDER.index(r), r) if r in REGION_ORDER else (len(REGION_ORDER), r)


def pretty(name):
    if name == ALL or name in NAMED_REGIONS:
        return name
    return f"Region {name}"


def hake_category(g):
    if g is None:
        return "n/a"
    return "high" if g >= 0.7 else "medium" if g >= 0.3 else "low"


CAT_COLOR = {"high": TEAL, "medium": AMBER, "low": CORAL, "n/a": SLATE}


def p_text(p):
    if p is None:
        return "p = n/a"
    return "p &lt; 0.001" if p < 0.001 else f"p = {p:.3f}"


def share(a, b):
    return 100 * a / b if b else 0.0


